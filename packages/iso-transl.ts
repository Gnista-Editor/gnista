// Typing characters not on the keyboard with C-x 8, after Emacs's
// iso-transl.el: C-x 8 ' e makes é, C-x 8 " u makes ü, C-x 8 * d makes °
// and so on, through key-translation-map, so they work wherever a
// character is read, the minibuffer included.

for (const [keys, text] of translations()) {
  ember.defineKey("key-translation-map", `C-x 8 ${keys}`, [...text]);
}

